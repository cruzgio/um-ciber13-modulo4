#!/usr/bin/env bash
# ════════════════════════════════════════════════════════════════════════
#  Lab 2 · La política de fw-borde — instalador del escenario de Killercoda
#  Módulo 4 · CIBER13 · Universidad de Montevideo
#
#  Un solo archivo. Un solo comando. No hay que descomprimir ni copiar
#  carpetas a mano — que es justo donde se rompió el despliegue anterior.
#
#  USO
#    1. Copia este archivo DENTRO de tu repo ya clonado:
#         cd um-ciber13-modulo4
#    2. Ejecútalo:
#         bash crear-lab2.sh
#    3. Sube:
#         git add -A && git commit -m "Lab 2: politica de fw-borde" && git push
#
#  Crea la carpeta lab2-fw-borde/ con todo dentro y, lo importante,
#  ya con los permisos de ejecución puestos y marcados en git.
#
#  SHA-256 del contenido: 1775b7770294f662e20f0d65aca2586e78487d102c0f2f2c79015755cfc8b995
# ════════════════════════════════════════════════════════════════════════
set -euo pipefail

DESTINO="lab2-fw-borde"
ESPERADO="1775b7770294f662e20f0d65aca2586e78487d102c0f2f2c79015755cfc8b995"

echo
echo "  Lab 2 · La política de fw-borde"
echo "  ───────────────────────────────"

if [ -d "$DESTINO" ]; then
  echo
  echo "  Ya existe la carpeta $DESTINO/."
  read -r -p "  ¿La reemplazo? Se pierde todo lo que hayas editado dentro [s/N] " R
  case "$R" in s|S) rm -rf "$DESTINO" ;; *) echo "  Cancelado."; exit 0 ;; esac
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

LINEA=$(grep -n "^__CARGA__$" "$0" | tail -1 | cut -d: -f1)
tail -n +$((LINEA + 1)) "$0" | base64 -d > "$TMP/lab2.tgz"

if command -v sha256sum >/dev/null 2>&1; then
  REAL=$(sha256sum "$TMP/lab2.tgz" | cut -d' ' -f1)
  if [ "$REAL" != "$ESPERADO" ]; then
    echo "  ERROR: el contenido embebido no coincide con su huella. Descarga el archivo otra vez."
    exit 1
  fi
  echo "  Huella SHA-256 verificada."
fi

tar xzf "$TMP/lab2.tgz" -C .

chmod +x "$DESTINO/background.sh" "$DESTINO/foreground.sh"
chmod +x "$DESTINO"/assets/ct-* "$DESTINO"/assets/*.sh "$DESTINO"/assets/registro.py
echo "  Carpeta $DESTINO/ creada con permisos de ejecución."

if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  git add "$DESTINO" >/dev/null 2>&1 || true
  for f in "$DESTINO/background.sh" "$DESTINO/foreground.sh" \
           "$DESTINO"/assets/ct-* "$DESTINO"/assets/*.sh "$DESTINO"/assets/registro.py; do
    git update-index --chmod=+x "$f" >/dev/null 2>&1 || true
  done
  echo "  Permisos registrados en git (sobreviven al push)."
else
  echo "  AVISO: no estás dentro de un repositorio git."
  echo "  Mueve la carpeta a tu repo y allí ejecuta:"
  echo "    git update-index --chmod=+x $DESTINO/background.sh $DESTINO/foreground.sh"
fi

cat <<'FIN'

  ── Lo que falta ────────────────────────────────────────────────────

  1. Las banderas YA están generadas en lab2-fw-borde/assets/flags.env.
     No hay que inventar nada.

  2. Sube el escenario:
       git add -A && git commit -m "Lab 2: politica de fw-borde" && git push

  3. Un minuto después, ábrelo y pruébalo:
       https://killercoda.com/cruzgio/scenario/lab2-fw-borde

       ct-mapa                        ¿aparecen las cuatro zonas?
       ct-probar internet tienda 443  PASA
       ct-probar usuarios erp 1433    CAE  (eso lo escriben ellos)
       ct-check A                     falla solo los flujos 3 y 6

  4. Carga los seis retos en CTFd:
       Admin -> Challenges -> Import CSV  con  CTFd_Lab2_Retos.csv
       Categoria "Lab 2":  A Minimo 3 · A Completo 2 · A Rescate 1
                           B Minimo 2 · B Completo 1 · B Rescate 1

FIN
exit 0
