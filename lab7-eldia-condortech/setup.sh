# 3) restic: binario oficial (3 intentos) y, si falla, el paquete de la distribución
instalar_restic() {
  for i in 1 2 3; do
    curl -fsSL --max-time 60 -o /tmp/restic.bz2 https://github.com/restic/restic/releases/download/v0.17.3/restic_0.17.3_linux_amd64.bz2 \
      && bunzip2 -f /tmp/restic.bz2 && install -m 755 /tmp/restic /usr/local/bin/restic && return 0
    sleep 4
  done
  apt-get update -qq && apt-get install -y -qq restic && return 0
  return 1
}
command -v restic >/dev/null || instalar_restic
restic version && echo ok > $CT/estado-restic

# 4) Copia inmutable: rest-server en modo append-only (3 intentos); si no se puede, queda como repositorio local
instalar_rs() {
  for i in 1 2 3; do
    curl -fsSL --max-time 60 -o /tmp/rs.tgz https://github.com/restic/rest-server/releases/download/v0.13.0/rest-server_0.13.0_linux_amd64.tar.gz \
      && tar xzf /tmp/rs.tgz -C /tmp && install -m 755 /tmp/rest-server_0.13.0_linux_amd64/rest-server /usr/local/bin/rest-server && return 0
    sleep 4
  done
  return 1
}
if command -v rest-server >/dev/null || instalar_rs; then
  nohup rest-server --path /srv/inmutable --listen 127.0.0.1:8080 --append-only --no-auth >/var/log/rest-server.log 2>&1 &
  for i in $(seq 1 10); do curl -fs -o /dev/null http://127.0.0.1:8080/erp/config && break; sleep 1; done
  curl -fs -o /dev/null http://127.0.0.1:8080/erp/config && echo rest > $CT/estado-copia || echo local > $CT/estado-copia
else
  echo local > $CT/estado-copia
fi

