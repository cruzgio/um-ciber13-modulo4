#!/bin/bash
# crear-lab6.sh — crea el repositorio del escenario Killercoda del Lab 6 (Cóndor Tech, clase 11).
# Compatible con macOS (base64 por stdin, shasum). Uso: bash crear-lab6.sh [directorio-destino]
#
# ANTES DE EJECUTAR:
#  - El escenario se publica como un repositorio NUEVO en tu cuenta de Killercoda (killercoda.com/cruzgio),
#    o como una carpeta nueva dentro del repo que ya usas para los labs (en ese caso pasa esa carpeta como destino).
#  - Necesitas git configurado y acceso al remoto.
#  - El escenario usa el backend «ubuntu» de Killercoda (trae Docker). Trivy 0.75.0 se instala al arrancar.
set -e
SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"
DEST="${1:-.}"
mkdir -p "$DEST" && cd "$DEST"
TMP=$(mktemp -d)
sed -n '/^__CARGA__$/,$p' "$SELF" | tail -n +2 | base64 -d > "$TMP/lab6.tar.gz"
if command -v shasum >/dev/null 2>&1; then H=$(shasum -a 256 "$TMP/lab6.tar.gz" | cut -d' ' -f1); else H=$(sha256sum "$TMP/lab6.tar.gz" | cut -d' ' -f1); fi
[ "$H" = "7c070ca509d4908660300bfbbf5a45a0f0f3cc05af4cde20fc460d8665f7980e" ] || { echo "✘ La carga embebida está corrupta (sha256 no coincide)"; exit 1; }
tar xzf "$TMP/lab6.tar.gz"
chmod +x lab6-vulnerabilidades-condortech/*.sh lab6-vulnerabilidades-condortech/assets/ct-*
rm -rf "$TMP"
echo "✔ Escenario creado en $(pwd)/lab6-vulnerabilidades-condortech"
echo
echo "Siguiente paso (desde la raíz del repositorio):"
echo '  git add -A && git commit -m "Lab 6: ct-uso y columna IMPACTO para el A1" && git push'
echo
echo "Luego en Killercoda: el escenario aparece como lab6-vulnerabilidades-condortech. Primera corrida: sigue la sección 2 de la guía docente."
exit 0
